"""OPERATIONAL: Harvey--Hittmeir 2022 Algorithm 4.3 (baseline) and three
sign-splitting variants.  Receives only N, public parameters (M, m0, split, g,
balanced ratio bound c) and a seed.  Never uses p, q, phi(N) or group orders.
Every inversion mod N is gcd-checked; every nontrivial gcd is returned.

Variants (notes/signsplit_prereg.md):
  V0  HH baseline: one Prop. 3.3 reduction and one giant step per (sigma, sigma0),
      sigma over all units mod M; shared baby list beta^{M^2 i}, 0 <= i <= 2 lambda.
  V1  shared-lattice HH: one reduction per (square class gamma, sigma0); the 2^t
      giants of the class are generated by a Gray-code walk over eps using the
      signed subset sum tau(sigma(eps)) = Delta0 + sum eps_i Delta_i - M^2 c(eps).
      Same giant/baby lists as V0 (only construction cost differs).
  V2  per-group sign meet-in-the-middle (the user's claim taken literally): per
      group (gamma, sigma0), left list beta^{aN+b-Delta0-S_L(eps_L)-M^2(base+W_R h)}
      (2^{t_L} g elements), right list beta^{M^2 i + S_R(eps_R)} (2^{t_R} W_R
      elements, group-specific because Delta_R depends on (a,b)).  Carries widen
      the window by chi - clo.
  V3  sign-collapse ("anti-lock") on a set A of odd primes: weights with
      m | a, m | b and (a/m) N + (b/m) sigma^2 == 0 (mod m), so a q + b p == 0
      (mod m^2) for BOTH signs +-sigma mod m; one giant per (sigma_L, +-sigma_A),
      shared baby list, lattice index M * prod_A m^2.

Collision detection: exact matches mod N by sort-and-match (Lemma 2.4 recovery),
then Harvey's Alg. 4.1 (product tree + Bluestein) for V0/V1/V3, and product
tree + remainder tree (general multipoint) for V2's non-progression right lists.
"""
from __future__ import annotations

import random
from math import gcd, isqrt
from typing import Dict, List, Optional, Sequence, Tuple

from src.common.metrics import Metrics
from src.cycloharvey.calibration import ceil_sqrt_ratio
from src.cycloharvey.operational import (FactorFound, find_collisions, multipoint_eval,
                                         product_tree, recover_from_u)

from .identity import (carry, carry_range, crt, factor_squarefree, gamma_of,
                       sign_decomposition, sqrt_mod_prime, tau)


# --------------------------------------------------------------------------
# counted arithmetic mod N
# --------------------------------------------------------------------------
class Ring:
    def __init__(self, N: int, beta: int, met: Metrics):
        self.N, self.met = N, met
        self._check(beta, "base")
        self.beta = beta
        self.beta_inv = pow(beta, -1, N)
        met.inc("inv")

    def _check(self, x: int, how: str) -> int:
        self.met.inc("gcd")
        g = gcd(x % self.N, self.N)
        if 1 < g < self.N:
            raise FactorFound(g, how)
        if g == self.N:
            raise ZeroDivisionError(how)
        return g

    def bpow(self, e: int) -> int:
        """beta^e mod N for any integer e; counts square-and-multiply mults."""
        if e == 0:
            return 1
        base = self.beta if e > 0 else self.beta_inv
        e = abs(e)
        self.met.inc("rn_mul", e.bit_length() + bin(e).count("1") - 2)
        self.met.inc("rn_pow")
        return pow(base, e, self.N)

    def mul(self, x: int, y: int) -> int:
        self.met.inc("rn_mul")
        return x * y % self.N


# --------------------------------------------------------------------------
# lattice of admissible weights and HH Prop. 3.3
# --------------------------------------------------------------------------
def weight_lattice(N: int, primes: Sequence[int], sigma: int, anti: Sequence[int] = ()) -> Tuple[int, int, int]:
    """Lattice {(a, b) : A0 | a, b == g a (mod Q)}.  For a 'lock' prime m:
    b == (N/sigma^2) a (mod m).  For an 'anti' prime m (odd): b == -(N/sigma^2) a
    (mod m^2) and m | a.  Returns (A0, g, Q); index = A0 * Q."""
    res, mods, A0 = [], [], 1
    for m in primes:
        if m in anti:
            mm = m * m
            res.append((-N * pow(sigma * sigma, -1, mm)) % mm)
            mods.append(mm)
            A0 *= m
        else:
            res.append((N * pow(sigma * sigma, -1, m)) % m)
            mods.append(m)
    Q = 1
    for q in mods:
        Q *= q
    g = crt(res, mods) if mods else 0
    return A0, g, Q


def gauss_reduce(u: Tuple[int, int], v: Tuple[int, int], met: Metrics) -> Tuple[int, int]:
    def n2(w):
        return w[0] * w[0] + w[1] * w[1]
    if n2(u) > n2(v):
        u, v = v, u
    while True:
        met.inc("gauss_iter")
        uu = n2(u)
        dot = u[0] * v[0] + u[1] * v[1]
        q = (2 * dot + uu) // (2 * uu)          # nearest integer to dot/uu
        v = (v[0] - q * u[0], v[1] - q * u[1])
        if n2(v) < uu:
            u, v = v, u
        else:
            return u


def prop33(N: int, m0: int, sigma0: int, lat: Tuple[int, int, int], met: Metrics) -> Tuple[int, int]:
    """HH Prop. 3.3 for the lattice (A0, g, Q) of index I = A0 Q: returns (a, b) != 0
    in the lattice with |-aN/s0 + b s0| <= 2 N^{1/2} I^{1/2} m0^{-1/2} and
    |aN/s0| <= 2 N^{1/2} I^{1/2} m0^{1/2}."""
    A0, g, Q = lat
    I = A0 * Q
    met.inc("lattice_red")
    s2 = sigma0 * sigma0

    def tr(a, b):
        return (N * a, -N * m0 * a + m0 * s2 * b)
    u = tr(A0, (g * A0) % Q)
    v = tr(0, Q)
    c, d = gauss_reduce(u, v, met)
    X2 = 4 * N * I * m0 * s2                      # (2 sqrt(det))^2
    assert c * c <= X2 and d * d <= X2, "Prop 3.3 bound violated"
    assert c % N == 0
    a = c // N
    num = d + N * m0 * a
    assert num % (m0 * s2) == 0
    b = num // (m0 * s2)
    return a, b


# --------------------------------------------------------------------------
# parameters shared by all variants
# --------------------------------------------------------------------------
def buckets(N: int, m0: int, c_num: int = 2, c_den: int = 1) -> List[int]:
    """sigma0 values covering the balanced range [sqrt(N/c), sqrt(N)] (p < q)."""
    s0 = ceil_sqrt_ratio(N * c_den, c_num)
    hi = isqrt(N)
    out = []
    while s0 <= hi:
        out.append(s0)
        s0 = -(-(s0 * (m0 + 1)) // m0)
    return out


def lam(N: int, M: int, m0: int, I: int) -> int:
    """lambda = ceil(4 N^{1/2} I^{1/2} m0^{-3/2} / M^2) (exact)."""
    return ceil_sqrt_ratio(16 * N * I, m0 ** 3 * M ** 4)


def units(M: int) -> List[int]:
    return [s for s in range(1, M) if gcd(s, M) == 1] if M > 1 else [0]


def square_classes(N: int, M: int) -> Dict[int, List[int]]:
    """gamma -> sorted list of units sigma with N/sigma^2 == gamma (mod M)."""
    cls: Dict[int, List[int]] = {}
    for s in units(M):
        g = gamma_of(s, N, M) if M > 1 else 0
        cls.setdefault(g, []).append(s)
    return cls


def tau0_floor(a: int, b: int, N: int, sigma0: int, M2: int) -> int:
    """floor((a N / sigma0 + b sigma0) / M^2) exactly."""
    return (a * N + b * sigma0 * sigma0) // (sigma0 * M2)


# --------------------------------------------------------------------------
# collision back-end
# --------------------------------------------------------------------------
def _exact_and_collide(N: int, R: Ring, babies: Dict[int, int], kappa: int, alpha: int,
                       giants: List[int], meta: List[Tuple], met: Metrics,
                       u_of: callable) -> Optional[Dict]:
    """Sort-and-match exact matches (HH Step 12), then Alg. 4.1 (Step 13)."""
    rest, rmeta = [], []
    for v, mt in zip(giants, meta):
        met.inc("match_probe")
        if v in babies:
            met.inc("exact_match")
            a, b, u = u_of(mt, babies[v])
            d = recover_from_u(N, a, b, u)
            if d:
                return {"factor": d, "status": "exact_match", "hit": {"target": list(mt), "baby": babies[v]}}
        else:
            rest.append(v)
            rmeta.append(mt)
    met.set("giant_after_match", len(rest))
    d = find_collisions(N, alpha, kappa, rest, met)
    if d:
        hit = met.fields.get("hit")
        return {"factor": d, "status": "collision",
                "hit": {"baby": hit[0], "target": list(rmeta[hit[1]])} if hit else None}
    return None


def _baby_list(R: Ring, M2: int, count: int, met: Metrics) -> Tuple[Dict[int, int], int]:
    """beta^{M^2 i}, 0 <= i < count; HH Step 3 gcd checks."""
    alpha = R.bpow(M2)
    babies, x = {}, 1
    for i in range(count):
        if i:
            R._check(x - 1, "baby_order")       # HH Step 3 (raises on factor / order)
        if x in babies:
            raise ZeroDivisionError("small_order")
        babies[x] = i
        x = R.mul(x, alpha)
    return babies, alpha


def _start(N: int, seed: int, met: Metrics, tag: str) -> Ring:
    rng = random.Random(f"signsplit|{tag}|{N}|{seed}")
    beta = rng.randrange(2, N - 1)
    return Ring(N, beta, met)


# --------------------------------------------------------------------------
# V0 / V1 / V3: shared baby list
# --------------------------------------------------------------------------
def hh_search(N: int, M: int, m0: int, variant: str = "V0", anti: Sequence[int] = (),
              seed: int = 0, count_only: bool = False, c_num: int = 2) -> Dict:
    """variant in {"V0", "V1", "V3"}; anti = odd primes of M collapsed (V3 only)."""
    met = Metrics(variant=variant, M=M, m0=m0, anti=list(anti))
    primes = factor_squarefree(M) if M > 1 else []
    anti = tuple(sorted(anti)) if variant == "V3" else ()
    assert all(m in primes and m % 2 for m in anti)
    if M > 1 and gcd(M, N) != 1:
        met.inc("gcd")
        return {"factor": gcd(M, N), "status": "gcd_M", "met": met.to_record()}
    M2 = M * M
    MA = 1
    for m in anti:
        MA *= m
    I = M * MA * MA
    lmb = lam(N, M, m0, I)
    kappa = 2 * lmb + 1
    S0 = buckets(N, m0, c_num)
    cls = square_classes(N, M)
    # giant index set
    if variant == "V3":
        # one representative per (sigma_L, +-sigma_A): canonical sign on A primes
        reps = [s for s in units(M) if all((s % m) <= m // 2 for m in anti)]
    else:
        reps = units(M)
    n_giant = len(reps) * len(S0)
    met.set("baby", kappa)
    met.set("giant", n_giant)
    met.set("buckets", len(S0))
    met.set("lambda", lmb)
    met.set("index", I)
    met.set("groups", len(cls) * len(S0))
    if count_only:
        met.set("work", kappa + n_giant)
        return {"factor": None, "status": "count_only", "met": met.to_record()}
    try:
        R = _start(N, seed, met, variant)
        babies, alpha = _baby_list(R, M2, kappa, met)
        giants, meta = [], []
        if variant in ("V0", "V3"):
            for s in reps:
                lat = weight_lattice(N, primes, s, anti) if M > 1 else (1, 0, 1)
                for s0 in S0:
                    a, b = prop33(N, m0, s0, lat, met)
                    t = tau(a, b, s, N, M) if M > 1 else 0
                    j = M2 * (tau0_floor(a, b, N, s0, M2) - lmb) + t
                    giants.append(R.bpow(a * N + b - j))
                    meta.append((s, s0, a, b, j))
        else:  # V1: per square class, Gray-code walk over the sign vector
            bM2 = {k: R.bpow(k * M2) for k in (-2, -1, 1, 2)}
            for gm, members in cls.items():
                rr = []
                for m in primes:
                    roots = sqrt_mod_prime((N * pow(gm, -1, m)) % m, m)
                    rr.append(min(r for r in roots if r % m) if m > 2 else 1)
                lat = weight_lattice(N, primes, crt(rr, primes), ())
                for s0 in S0:
                    a, b = prop33(N, m0, s0, lat, met)
                    dec = sign_decomposition(a, b, rr, primes, N)
                    t = len(dec["Delta"])
                    base_e = a * N + b - M2 * (tau0_floor(a, b, N, s0, M2) - lmb)
                    eps = [1] * t
                    c = carry(eps, dec)
                    S = dec["Delta0"] + sum(dec["Delta"])
                    v = R.bpow(base_e - (S - M2 * c))
                    up = [R.bpow(2 * d) for d in dec["Delta"]]       # beta^{+2 Delta_i}
                    dn = [R.bpow(-2 * d) for d in dec["Delta"]]
                    from .identity import sigma_of_eps
                    for k in range(1 << t):
                        if k:
                            i = (k & -k).bit_length() - 1             # Gray-code flip
                            eps[i] = -eps[i]
                            S_new = S + 2 * eps[i] * dec["Delta"][i]
                            c_new = S_new // M2
                            # exponent -tau changes by -(S_new - S) + M2 (c_new - c)
                            v = R.mul(v, dn[i] if eps[i] == 1 else up[i])
                            dc = c_new - c
                            if dc:
                                v = R.mul(v, bM2[dc])
                            S, c = S_new, c_new
                        s = sigma_of_eps(eps, rr, primes)
                        j = M2 * (tau0_floor(a, b, N, s0, M2) - lmb) + (S - M2 * c)
                        giants.append(v)
                        meta.append((s, s0, a, b, j))
        assert len(giants) == n_giant, (len(giants), n_giant)

        def u_of(mt, i):
            s, s0, a, b, j = mt
            return a, b, M2 * i + j
        out = _exact_and_collide(N, R, babies, kappa, alpha, giants, meta, met, u_of)
        if out:
            out["met"] = met.to_record()
            return out
        return {"factor": None, "status": "none", "met": met.to_record()}
    except FactorFound as e:
        return {"factor": e.d, "status": "gcd_" + e.how, "met": met.to_record()}
    except ZeroDivisionError as e:
        return {"factor": None, "status": "fail_" + str(e), "met": met.to_record()}


# --------------------------------------------------------------------------
# V2: per-group meet-in-the-middle over the sign vector
# --------------------------------------------------------------------------
def v2_counts(N: int, M: int, m0: int, tR: int, g: int, c_num: int = 2) -> Dict:
    """Exact list sizes of V2 without ring arithmetic (needs the per-group carry
    ranges, so it runs the lattice reductions)."""
    met = Metrics()
    primes = factor_squarefree(M)
    M2 = M * M
    lmb = lam(N, M, m0, M)
    S0 = buckets(N, m0, c_num)
    cls = square_classes(N, M)
    left = right = 0
    for gm in cls:
        rr = []
        for m in primes:
            roots = sqrt_mod_prime((N * pow(gm, -1, m)) % m, m)
            rr.append(min(r for r in roots if r % m) if m > 2 else 1)
        lat = weight_lattice(N, primes, crt(rr, primes), ())
        for s0 in S0:
            a, b = prop33(N, m0, s0, lat, met)
            dec = sign_decomposition(a, b, rr, primes, N)
            t = len(dec["Delta"])
            tl = t - tR
            clo, chi = carry_range(dec)
            K = 2 * lmb + 1 + chi - clo
            WR = -(-K // g)
            left += (1 << tl) * g
            right += (1 << tR) * WR
    return {"left": left, "right": right, "work": left + right, "groups": len(cls) * len(S0),
            "lambda": lmb, "lattice_red": met.get("lattice_red")}


def v2_search(N: int, M: int, m0: int, tR: int, g: int = 1, seed: int = 0,
              c_num: int = 2) -> Dict:
    met = Metrics(variant="V2", M=M, m0=m0, tR=tR, g=g)
    primes = factor_squarefree(M)
    if gcd(M, N) != 1:
        met.inc("gcd")
        return {"factor": gcd(M, N), "status": "gcd_M", "met": met.to_record()}
    M2 = M * M
    lmb = lam(N, M, m0, M)
    S0 = buckets(N, m0, c_num)
    cls = square_classes(N, M)
    try:
        R = _start(N, seed, met, "V2")
        lefts, lmeta, rights, rmeta = [], [], [], []
        alpha = R.bpow(M2)
        for gm in cls:
            rr = []
            for m in primes:
                roots = sqrt_mod_prime((N * pow(gm, -1, m)) % m, m)
                rr.append(min(r for r in roots if r % m) if m > 2 else 1)
            lat = weight_lattice(N, primes, crt(rr, primes), ())
            for s0 in S0:
                a, b = prop33(N, m0, s0, lat, met)
                dec = sign_decomposition(a, b, rr, primes, N)
                D = dec["Delta"]
                t = len(D)
                tl = t - tR
                clo, chi = carry_range(dec)
                K = 2 * lmb + 1 + chi - clo
                WR = -(-K // g)
                base = a * N + b - dec["Delta0"] - M2 * (tau0_floor(a, b, N, s0, M2) - lmb - chi)
                gid = len(lmeta)
                for k in range(1 << tl):
                    SL = sum((-d if (k >> i) & 1 else d) for i, d in enumerate(D[:tl]))
                    for h in range(g):
                        e = base - SL - M2 * WR * h
                        lefts.append(R.bpow(e))
                        lmeta.append((gm, s0, a, b, e))
                for k in range(1 << tR):
                    SR = sum((-d if (k >> i) & 1 else d) for i, d in enumerate(D[tl:]))
                    x = R.bpow(SR)
                    for i in range(WR):
                        rights.append(x)
                        rmeta.append((gm, s0, SR, i))
                        x = R.mul(x, alpha)
        met.set("left", len(lefts))
        met.set("right", len(rights))
        met.set("work", len(lefts) + len(rights))
        # generic one-sided collision detection: product tree of the left list,
        # multipoint evaluation at every right element, gcds.
        f = product_tree(lefts, N, met)
        vals = multipoint_eval(f, rights, N, met)
        for idx, val in enumerate(vals):
            met.inc("gcd")
            gg = gcd(val, N)
            if gg == 1:
                continue
            if 1 < gg < N:
                return {"factor": gg, "status": "collision", "hit": {"right": list(rmeta[idx])},
                        "met": met.to_record()}
            # gg == N: locate; exact matches give u directly
            for h, lv in enumerate(lefts):
                met.inc("gcd_locate")
                g2 = gcd((lv - rights[idx]) % N, N)
                if 1 < g2 < N:
                    return {"factor": g2, "status": "collision",
                            "hit": {"right": list(rmeta[idx]), "left": list(lmeta[h])},
                            "met": met.to_record()}
                if g2 == N:
                    gm_, s0_, a_, b_, e_ = lmeta[h]
                    # beta^{e_} == beta^{M^2 i + S_R} with e_ = aN + b - (offset):
                    # u = a q + b p = (aN + b - e_) + M^2 i + S_R
                    u = (a_ * N + b_ - e_) + M2 * rmeta[idx][3] + rmeta[idx][2]
                    d = recover_from_u(N, a_, b_, u)
                    if d:
                        return {"factor": d, "status": "exact_match",
                                "hit": {"right": list(rmeta[idx]), "left": list(lmeta[h])},
                                "met": met.to_record()}
        return {"factor": None, "status": "none", "met": met.to_record()}
    except FactorFound as e:
        return {"factor": e.d, "status": "gcd_" + e.how, "met": met.to_record()}
