"""Analysis of divcover E1/E2 raw data -> experiments/analysis/divcover_tables.md.

    .venv/bin/python -m src.divcover.analyze
"""
from __future__ import annotations

import json
import math
import os
from collections import defaultdict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def load(path):
    return [json.loads(l) for l in open(os.path.join(ROOT, path)) if l.strip()]


def main():
    E1 = load("experiments/raw/divcover_exact.jsonl")
    E2 = load("experiments/raw/divcover_structured.jsonl")
    out = []
    w = out.append
    w("# divcover tables (generated by src/divcover/analyze.py)\n")
    # ---------------- E1 main table
    w("## E1: exact minimal heights H* vs random-model prediction (prime-mode model)\n")
    w("`H*` exact min height over all shapes of the rank (`>Hmax` = none found <= Hmax; "
      "`cens` = some shape timed out, value is an upper bound on the min over shapes, "
      "or a lower bound Hmax if none found). ρ = log H* / log H_pred.\n")
    w("| n | L | r | H_pred | H*_prime | ρ_prime | H*_full | ρ_full(vs prime model) |")
    w("|---|---|---|---|---|---|---|---|")
    cell = {}
    for r in E1:
        cell[(r["n"], r["L"], r["rank"], r["mode"])] = r
    keys = sorted({(n, L, k) for (n, L, k, m) in cell})
    signal = []
    rho_rows = []
    for (n, L, k) in keys:
        rp = cell.get((n, L, k, "prime"))
        rf = cell.get((n, L, k, "full"))
        lp = (rp or rf)["logH_pred_prime"]

        def fmt(rec):
            if rec is None:
                return "—", "—", None
            cens = " cens" if rec["timed_out_shapes"] else ""
            if rec["H_star"] is None:
                return f">{rec['Hmax']}{cens}", f">{math.log(rec['Hmax'])/lp:.2f}", None
            rho = math.log(rec["H_star"]) / lp
            return f"{rec['H_star']}{cens}", f"{rho:.2f}", rho

        hp, rhp, rho_p = fmt(rp)
        hf, rhf, rho_f = fmt(rf)
        w(f"| {n} | {L} | {k} | {math.exp(lp):.4g} | {hp} | {rhp} | {hf} | {rhf} |")
        if rho_p is not None:
            rho_rows.append((n, L, k, rho_p, rp["timed_out_shapes"] != []))
            if n >= 40 and L <= n / 4 and rho_p <= 0.5:
                signal.append((n, L, k, rho_p))
    w("")
    w(f"**Pre-registered E1 structure signal** (prime, n>=40, L<=n/4, ρ<=0.5): "
      f"{'YES ' + str(signal) if signal else 'NONE'}\n")
    # rho statistics per rank (prime, uncensored, n >= 40)
    w("### ρ_prime summary (uncensored cells, n >= 40)\n")
    w("| rank | cells | min ρ | median ρ | max ρ |")
    w("|---|---|---|---|---|")
    for k in (1, 2, 3):
        vals = [rho for (n, L, kk, rho, c) in rho_rows if kk == k and n >= 40 and not c]
        if vals:
            w(f"| {k} | {len(vals)} | {min(vals):.2f} | {float(np.median(vals)):.2f} | {max(vals):.2f} |")
    w("")
    # ---------------- rank comparison at fixed (n, L)
    w("### Rank comparison (prime mode): log H*_r and (r+1)·log H*_r\n")
    w("Random model: log H_r ≈ (mass term)/(r+1), so (r+1)·log H*_r should be roughly rank-independent.\n")
    w("| n | L | logH*_1 | logH*_2 | logH*_3 | 2·logH*_1 | 3·logH*_2 | 4·logH*_3 |")
    w("|---|---|---|---|---|---|---|---|")
    for (n, L) in sorted({(n, L) for (n, L, k) in keys}):
        vals = {}
        for k in (1, 2, 3):
            rec = cell.get((n, L, k, "prime"))
            if rec and rec["H_star"] is not None and not rec["timed_out_shapes"]:
                vals[k] = math.log(rec["H_star"])
        if len(vals) >= 2:
            def g(k):
                return f"{vals[k]:.2f}" if k in vals else "—"

            def g2(k):
                return f"{(k+1)*vals[k]:.2f}" if k in vals else "—"
            w(f"| {n} | {L} | {g(1)} | {g(2)} | {g(3)} | {g2(1)} | {g2(2)} | {g2(3)} |")
    w("")
    # ---------------- L*(n; alpha)
    w("## E1: L*(n; α) = least grid L (ranks <= 3) with H* <= exp(n^α)  [descriptive only]\n")
    for mode in ("prime", "full"):
        for alpha in (1 / 3, 1 / 2):
            w(f"### mode={mode}, α={alpha:.3f}\n")
            w("| n | exp(n^α) | L* r<=1 | L* r<=2 | L* r<=3 |")
            w("|---|---|---|---|---|")
            fits = defaultdict(list)
            for n in sorted({k[0] for k in keys}):
                cap = math.exp(n ** alpha)
                row = []
                for rmax in (1, 2, 3):
                    best = None
                    for (nn, L, k, m), rec in cell.items():
                        if nn != n or m != mode or k > rmax:
                            continue
                        if rec["H_star"] is not None and rec["H_star"] <= cap:
                            best = L if best is None else min(best, L)
                    row.append(best)
                    if best is not None:
                        fits[rmax].append((n, best))
                w(f"| {n} | {cap:.4g} | " + " | ".join(str(x) if x else "—" for x in row) + " |")
            for rmax, pts in fits.items():
                if len(pts) >= 3:
                    x = np.log([p[0] for p in pts]); y = np.log([p[1] for p in pts])
                    slope = np.polyfit(x, y, 1)[0]
                    w(f"\n- rank<= {rmax}: fitted slope d log L*/d log n = {slope:.3f} "
                      f"(β_fit = {slope/2:.3f}) on {len(pts)} points")
            w("")
    # ---------------- E2
    w("## E2(a): CRT/LLL designs (prime mode)\n")
    w("| n | r | shape | L | log H | α_eff | β_eff | covered | mass/(r+1) |")
    w("|---|---|---|---|---|---|---|---|---|")
    succ = []
    for r in E2:
        if r["family"] != "crt_lll":
            continue
        w(f"| {r['n']} | {r['rank']} | {r['shape']} | {r['L']} | {r['logH']:.1f} | "
          f"{r['alpha_eff']:.3f} | {r['beta_eff']:.3f} | {r['covered_all']} | "
          f"{r['minkowski_logH_est']:.1f} |")
        if r["covered_all"] and r["alpha_eff"] < 0.4 and r["beta_eff"] < 0.4:
            succ.append(r)
    w(f"\n**Pre-registered E2 success** (α_eff<0.4, β_eff<0.4, verified): "
      f"{'YES' if succ else 'NONE'}\n")
    w("## E2(b): polynomial-value (cyclotomic) GAPs\n")
    w("| n | t | rank | K | box | #primes>box | covered | random expect. | ratio |")
    w("|---|---|---|---|---|---|---|---|---|")
    sig = []
    for r in E2:
        if r["family"] != "poly_values":
            continue
        if r.get("vacuous"):
            w(f"| {r['n']} | {r['t']} | {r['rank']} | {r['K']} | {r['box']} | 0 | vacuous | — | — |")
            continue
        ratio = r["ratio_covered_over_expected"]
        w(f"| {r['n']} | {r['t']} | {r['rank']} | {r['K']} | {r['box']} | {r['n_primes_above_box']} | "
          f"{r['covered']} | {r['expected_random']:.1f} | {ratio:.2f} |")
        if r["n"] == 10000 and ratio is not None and ratio >= 2:
            sig.append(r)
    w(f"\n**Pre-registered E2(b) structure signal** (ratio>=2 at n=10^4): {'YES' if sig else 'NONE'}\n")
    os.makedirs(os.path.join(ROOT, "experiments/analysis"), exist_ok=True)
    open(os.path.join(ROOT, "experiments/analysis/divcover_tables.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
