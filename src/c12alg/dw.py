"""c12alg: design DW objects and the two-point smoothing construction (notes/c12alg_results.md §2-§3).

DIAGNOSTIC / HARNESS code: no factoring, no hidden data.  Exact integer arithmetic throughout.

Conventions (paper2 def:field, with the multiplier moved outside, pc3 §6.2):
  * G_g(x, y) = g1*x - g0*y;
  * Fhat_{g,N} = base-(g0, g1) expansion of N (paper2 lem:GB with T_d = N): coefficients a[0..d] of
    x^i y^(d-i), Fhat(g0, g1) = N;
  * R_c(x, y) = sum_i c_i x^(d-1-i) y^i, v(P) = (a^(d-1-i) b^i)_i, so R_c(P) = <c, v(P)>;
  * design DW:  F = w*Fhat_{g,N} + G*R_c,  F(g0, g1) = w*N,  w a uniform INTEGER.
"""
from __future__ import annotations

from fractions import Fraction
from math import gcd
from typing import Dict, List, Sequence, Tuple

import numpy as np

from src.thmA.numfield import gbe, hom_eval


# ----------------------------------------------------------------------------- forms and values
def fhat(N: int, d: int, g0: int, g1: int) -> List[int]:
    """Base-(g0, g1) expansion of N (multiplier outside): sum a_i g0^i g1^(d-i) = N."""
    return gbe(N, d, g0, g1)


def v_of(P: Tuple[int, int], d: int) -> List[int]:
    a, b = P
    return [a ** (d - 1 - i) * b ** i for i in range(d)]


def G_of(g: Tuple[int, int], P: Tuple[int, int]) -> int:
    return g[1] * P[0] - g[0] * P[1]


def dw_coeffs(N: int, w: int, d: int, g0: int, g1: int, c: Sequence[int]) -> List[int]:
    """Coefficients f[0..d] (of x^i, f(x) = F(x, 1)) of F = w*Fhat_N + (g1 x - g0) R_c(x, 1)."""
    a = fhat(N, d, g0, g1)
    f = [w * ai for ai in a]
    for i, ci in enumerate(c):
        j = d - 1 - i
        f[j + 1] += g1 * ci
        f[j] -= g0 * ci
    assert hom_eval(f, g0, g1) == N * w
    return f


def dw_value(N: int, w: int, d: int, g: Tuple[int, int], c: Sequence[int], P: Tuple[int, int]) -> int:
    a = fhat(N, d, g[0], g[1])
    return w * hom_eval(a, P[0], P[1]) + G_of(g, P) * sum(ci * vi for ci, vi in zip(c, v_of(P, d)))


# ----------------------------------------------------------------------------- lattices
def det2(P: Tuple[int, int], Q: Tuple[int, int]) -> int:
    return P[0] * Q[1] - P[1] * Q[0]


def lam_mod(P1: Tuple[int, int], P2: Tuple[int, int]) -> Tuple[int, int]:
    """(lambda, D) with P1 = lambda*P2 (mod D), D = |det(P1, P2)| (pc3 Lemma LAT(a)).  D = 1 gives (0, 1)."""
    D = abs(det2(P1, P2))
    assert D > 0
    if D == 1:
        return 0, 1
    a2, b2 = P2[0] % D, P2[1] % D
    # P2 is primitive, so one coordinate is a unit mod every prime of D; solve with the extended gcd on (a2, b2, D)
    # find lambda with lambda*a2 = a1 and lambda*b2 = b1 mod D
    for lam in range(D):
        if (lam * a2 - P1[0]) % D == 0 and (lam * b2 - P1[1]) % D == 0:
            return lam, D
    raise AssertionError("no lambda: points not primitive?")


def hnf2(vecs: Sequence[Tuple[int, int]]) -> Tuple[Tuple[int, int], Tuple[int, int]]:
    """Basis ((p, 0), (r, s)) in upper-triangular (column) Hermite form of the lattice generated by integer vectors in Z^2,
    written as: lattice = {(x, y): y = s*k, x = p*j + r*k}.  Requires full rank."""
    # work on the y-coordinates first: gcd of second coordinates
    vs = [tuple(v) for v in vecs if v != (0, 0)]
    # reduce to two vectors spanning the same lattice by repeated gcd on second coordinate
    basis = list(vs)
    # gather: lattice of first coords of vectors with y = 0, and one vector with minimal |y|
    while True:
        nz = [v for v in basis if v[1] != 0]
        if len(nz) <= 1:
            break
        nz.sort(key=lambda v: abs(v[1]))
        piv = nz[0]
        new = [piv]
        for v in basis:
            if v is piv:
                continue
            if v[1] != 0:
                k = v[1] // piv[1]
                v = (v[0] - k * piv[0], v[1] - k * piv[1])
            if v != (0, 0):
                new.append(v)
        basis = new
    nz = [v for v in basis if v[1] != 0]
    assert len(nz) == 1, "not full rank"
    piv = nz[0]
    if piv[1] < 0:
        piv = (-piv[0], -piv[1])
    p = 0
    for v in basis:
        if v[1] == 0:
            p = gcd(p, v[0])
    assert p > 0, "not full rank"
    return (p, 0), (piv[0] % p, piv[1])


def in_lattice(z: Tuple[int, int], basis) -> bool:
    (p, _), (r, s) = basis
    if z[1] % s:
        return False
    k = z[1] // s
    return (z[0] - r * k) % p == 0


def image_lattice(P1, P2, d: int):
    """HNF basis of Gamma = Phi(Z^d), Phi(c) = (R_c(P1), R_c(P2))."""
    v1, v2 = v_of(P1, d), v_of(P2, d)
    return hnf2([(v1[i], v2[i]) for i in range(d)])


# ----------------------------------------------------------------------------- Lemma TP construction
def kernel_basis(P1, P2, d: int) -> List[List[int]]:
    """e_m = Q * x^(d-3-m) y^m in c-coordinates, Q = (b1 x - a1 y)(b2 x - a2 y)  (lv5unif Kern-U)."""
    (a1, b1), (a2, b2) = P1, P2
    q = [b1 * b2, -(a1 * b2 + a2 * b1), a1 * a2]
    out = []
    for m in range(d - 2):
        e = [0] * d
        for t in range(3):
            e[m + t] = q[t]
        out.append(e)
    return out


def solve_int(P1, P2, d: int, z: Tuple[int, int]) -> List[int]:
    """Some integer x with Phi(x) = z (z must lie in Gamma).  Column operations with unimodular tracking."""
    v1, v2 = v_of(P1, d), v_of(P2, d)
    cols = [[v1[i], v2[i]] for i in range(d)]           # Phi(e_i) = cols[i]
    U = [[1 if i == j else 0 for j in range(d)] for i in range(d)]   # U[i] = preimage of cols[i]

    def combine(i, j, k):          # cols[i] -= k*cols[j]
        cols[i] = [cols[i][0] - k * cols[j][0], cols[i][1] - k * cols[j][1]]
        U[i] = [U[i][t] - k * U[j][t] for t in range(d)]

    # row 1 (second coordinate): gcd into column 0
    for row in (1, 0):
        start = 0 if row == 1 else 1
        while True:
            nz = [i for i in range(start, d) if cols[i][row] != 0]
            if len(nz) <= 1:
                break
            nz.sort(key=lambda i: abs(cols[i][row]))
            piv = nz[0]
            for i in nz[1:]:
                combine(i, piv, cols[i][row] // cols[piv][row])
        nz = [i for i in range(start, d) if cols[i][row] != 0]
        if nz and nz[0] != start:
            i = nz[0]
            cols[start], cols[i] = cols[i], cols[start]
            U[start], U[i] = U[i], U[start]
    # now cols[0] = (r, s), cols[1] = (p, 0), others zero
    r, s = cols[0]
    p = cols[1][0]
    assert z[1] % s == 0
    k = z[1] // s
    rem = z[0] - k * r
    assert rem % p == 0, "z not in Gamma"
    j = rem // p
    x = [k * U[0][t] + j * U[1][t] for t in range(d)]
    assert sum(x[i] * v1[i] for i in range(d)) == z[0] and sum(x[i] * v2[i] for i in range(d)) == z[1]
    return x


def representatives(P1, P2, d: int, j: int | None = None, k: int | None = None) -> List[Tuple[int, int]]:
    """R_jk = Gamma cap M[0,1)^2, M = (w_j | w_k) (columns), default (j, k) = (d-2, d-1)."""
    j = d - 2 if j is None else j
    k = d - 1 if k is None else k
    v1, v2 = v_of(P1, d), v_of(P2, d)
    wj, wk = (v1[j], v2[j]), (v1[k], v2[k])
    det = wj[0] * wk[1] - wj[1] * wk[0]
    assert det != 0
    basis = image_lattice(P1, P2, d)
    xs = [0, wj[0], wk[0], wj[0] + wk[0]]
    ys = [0, wj[1], wk[1], wj[1] + wk[1]]
    (p, _), (r, s) = basis
    out = []
    for kk in range(-(-min(ys) // s), max(ys) // s + 1):     # y = s*kk
        y = s * kk
        # x = r*kk + p*jj, and the parallelogram condition is linear in x for fixed y: bound x via the box
        x0 = r * kk
        jlo = -(-(min(xs) - x0) // p)
        jhi = (max(xs) - x0) // p
        for jj in range(jlo, jhi + 1):
            x = x0 + p * jj
            s1 = Fraction(x * wk[1] - y * wk[0], det)
            s2 = Fraction(-x * wj[1] + y * wj[0], det)
            if 0 <= s1 < 1 and 0 <= s2 < 1:
                out.append((x, y))
    assert len(out) * p * s == abs(det), (len(out), p * s, det)
    return out


def short_preimage(P1, P2, d: int, z: Tuple[int, int]) -> List[int]:
    """The vector x(z) of Lemma TP: Phi(x) = z, ||x||_inf <= 1 + 4 V^2 for z in R_{d-2,d-1}."""
    v1, v2 = v_of(P1, d), v_of(P2, d)
    j, k = d - 2, d - 1
    wj, wk = (v1[j], v2[j]), (v1[k], v2[k])
    det = wj[0] * wk[1] - wj[1] * wk[0]
    s1 = Fraction(z[0] * wk[1] - z[1] * wk[0], det)
    s2 = Fraction(-z[0] * wj[1] + z[1] * wj[0], det)
    p = [Fraction(0)] * d
    p[j], p[k] = s1, s2
    x0 = solve_int(P1, P2, d, z)
    diff = [p[t] - x0[t] for t in range(d)]               # lies in the real kernel
    E = kernel_basis(P1, P2, d)
    # solve diff = sum_m s_m e_m using the lower-triangular rows 0..d-3 (diagonal b1 b2)
    sm = [Fraction(0)] * (d - 2)
    for m in range(d - 2):
        acc = diff[m] - sum(sm[t] * E[t][m] for t in range(m))
        sm[m] = acc / E[m][m]
    for t in range(d):                                    # consistency on all coordinates
        assert diff[t] == sum(sm[m] * E[m][t] for m in range(d - 2))
    x = list(x0)
    for m in range(d - 2):
        fl = sm[m].numerator // sm[m].denominator
        for t in range(d):
            x[t] += fl * E[m][t]
    assert sum(x[i] * v1[i] for i in range(d)) == z[0] and sum(x[i] * v2[i] for i in range(d)) == z[1]
    return x


# ----------------------------------------------------------------------------- exact laws (E1a)
_KEYOFF = 1 << 31


def _enc(z1: np.ndarray, z2: np.ndarray) -> np.ndarray:
    return (z1.astype(np.int64) + _KEYOFF) * (1 << 32) + (z2.astype(np.int64) + _KEYOFF)


def law_phi(P1, P2, d: int, H: int) -> Tuple[np.ndarray, np.ndarray]:
    """Exact law of Phi(c), c uniform on [-H, H]^d: (sorted keys, counts).  Iterated sparse convolution."""
    v1, v2 = v_of(P1, d), v_of(P2, d)
    keys = np.array([_enc(np.array([0]), np.array([0]))[0]], dtype=np.int64)
    cnt = np.array([1], dtype=np.int64)
    cs = np.arange(-H, H + 1, dtype=np.int64)
    for i in range(d):
        z1 = (keys >> 32) - _KEYOFF
        z2 = (keys & ((1 << 32) - 1)) - _KEYOFF
        nz1 = (z1[:, None] + cs[None, :] * v1[i]).ravel()
        nz2 = (z2[:, None] + cs[None, :] * v2[i]).ravel()
        nk = _enc(nz1, nz2)
        nc = np.repeat(cnt, len(cs))
        keys, inv = np.unique(nk, return_inverse=True)
        cnt = np.bincount(inv, weights=nc).astype(np.int64)
    return keys, cnt


def shift_mix(keys: np.ndarray, cnt: np.ndarray, shifts: List[Tuple[int, int]]) -> Tuple[np.ndarray, np.ndarray]:
    """Law of X + Z with X ~ (keys, cnt) and Z uniform on `shifts`; counts multiplied by len(shifts)."""
    z1 = (keys >> 32) - _KEYOFF
    z2 = (keys & ((1 << 32) - 1)) - _KEYOFF
    allk = np.concatenate([_enc(z1 + s1, z2 + s2) for (s1, s2) in shifts])
    allc = np.tile(cnt, len(shifts))
    k2, inv = np.unique(allk, return_inverse=True)
    c2 = np.bincount(inv, weights=allc).astype(np.int64)
    return k2, c2


def tv_exact(k1, c1, n1: int, k2, c2, n2: int) -> Fraction:
    """TV between two finite laws given as (keys, counts) with totals n1, n2 (exact rational)."""
    allk = np.union1d(k1, k2)
    a = np.zeros(len(allk), dtype=object)
    b = np.zeros(len(allk), dtype=object)
    a[np.searchsorted(allk, k1)] = c1
    b[np.searchsorted(allk, k2)] = c2
    num = sum(abs(int(x) * n2 - int(y) * n1) for x, y in zip(a, b))
    return Fraction(num, 2 * n1 * n2)


def tv_lemma_bound(P1, P2, d: int, H: int) -> Fraction:
    V = max(abs(P1[0]), abs(P1[1]), abs(P2[0]), abs(P2[1]))
    return Fraction(d * (1 + 4 * V * V), 2 * H + 1)


# ----------------------------------------------------------------------------- Lemma U (unit residue)
def fhat_unit_mod_t(N: int, d: int, g: Tuple[int, int], P: Tuple[int, int]) -> bool | None:
    """Lemma CU check: if gcd(t, N) = 1 (t = |G(P)| > 1), is Fhat_N(P) a unit mod t?  None if hypothesis fails."""
    t = abs(G_of(g, P))
    if t <= 1 or gcd(t, N) != 1 or gcd(P[0], P[1]) != 1:
        return None
    a = fhat(N, d, g[0], g[1])
    return gcd(hom_eval(a, P[0], P[1]), t) == 1
