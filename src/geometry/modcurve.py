"""Modular curves X_0(N): orbifold invariants, the Eichler-Selberg trace formula, Manin symbols.

DIAGNOSTIC module: the closed formulas take the factorisation of N as input (that is the point: every known
formula for the area / genus / cusps / elliptic points of Gamma_0(N)\\H is a function of the factorisation).
The explicit P^1(Z/N) computations take only N but cost Theta(psi(N)) >= N, i.e. exponential in log N.
Exact arithmetic only (Fractions, integers, F_P).
"""
from __future__ import annotations

from fractions import Fraction
from math import gcd, isqrt
from typing import Dict, List, Tuple

Fact = Dict[int, int]  # {prime: exponent}


# ---------------------------------------------------------------------------------------------------------------
# small arithmetic helpers
# ---------------------------------------------------------------------------------------------------------------

def kronecker(a: int, n: int) -> int:
    """Kronecker symbol (a/n) for n > 0."""
    if n <= 0:
        raise ValueError("n > 0")
    res = 1
    while n % 2 == 0:
        n //= 2
        if a % 2 == 0:
            return 0
        if a % 8 in (3, 5):
            res = -res
    a %= n
    while a:
        while a % 2 == 0:
            a //= 2
            if n % 8 in (3, 5):
                res = -res
        a, n = n, a
        if a % 4 == 3 and n % 4 == 3:
            res = -res
        a %= n
    return res if n == 1 else 0


def factor_small(n: int) -> Fact:
    """Trial division (only for the small exact levels of E1)."""
    f: Fact = {}
    d = 2
    while d * d <= n:
        while n % d == 0:
            f[d] = f.get(d, 0) + 1
            n //= d
        d += 1
    if n > 1:
        f[n] = f.get(n, 0) + 1
    return f


def nval(f: Fact) -> int:
    out = 1
    for p, e in f.items():
        out *= p ** e
    return out


def divisors_of(f: Fact) -> List[int]:
    ds = [1]
    for p, e in f.items():
        ds = [d * p ** k for d in ds for k in range(e + 1)]
    return sorted(ds)


def _phi_f(f: Fact) -> int:
    out = 1
    for p, e in f.items():
        out *= (p - 1) * p ** (e - 1)
    return out


def squarefree(f: Fact) -> bool:
    return all(e == 1 for e in f.values())


# ---------------------------------------------------------------------------------------------------------------
# orbifold invariants of Gamma_0(N)\H from the factorisation (closed formulas)
# ---------------------------------------------------------------------------------------------------------------

def psi(f: Fact) -> int:
    """Index [SL_2(Z) : Gamma_0(N)] = N prod (1 + 1/p) = |P^1(Z/N)|; hyperbolic area of X_0(N) = (pi/3) psi(N)."""
    out = 1
    for p, e in f.items():
        out *= p ** (e - 1) * (p + 1)
    return out


def nu2(f: Fact) -> int:
    """Number of elliptic points of order 2 (cone points of angle pi)."""
    if f.get(2, 0) >= 2:
        return 0
    out = 1
    for p in f:
        out *= 1 + kronecker(-4, p)
    return out


def nu3(f: Fact) -> int:
    """Number of elliptic points of order 3."""
    if f.get(3, 0) >= 2:
        return 0
    out = 1
    for p in f:
        out *= 1 + kronecker(-3, p)
    return out


def nu_inf(f: Fact) -> int:
    """Number of cusps = sum_{d | N} phi(gcd(d, N/d)); = 2^omega(N) for squarefree N."""
    N = nval(f)
    return sum(_phi_f(factor_small(gcd(d, N // d))) for d in divisors_of(f))


def genus(f: Fact) -> int:
    g = 1 + Fraction(psi(f), 12) - Fraction(nu2(f), 4) - Fraction(nu3(f), 3) - Fraction(nu_inf(f), 2)
    assert g.denominator == 1
    return int(g)


# ---------------------------------------------------------------------------------------------------------------
# explicit P^1(Z/N): takes only N, costs Theta(psi(N))
# ---------------------------------------------------------------------------------------------------------------

def p1_normalize(c: int, d: int, N: int) -> Tuple[int, int]:
    """Canonical representative of (c : d) in P^1(Z/N), using only N (no factorisation).

    Scale so that c becomes g = gcd(c, N); the stabiliser of g in (Z/N)^* is {u = 1 mod N/g}; take the least d."""
    c %= N
    d %= N
    if N == 1:
        return (0, 0)
    g = gcd(c, N)
    m = N // g
    c1 = c // g
    # unit u with u*c = g mod N: u = c1^{-1} mod m, lifted to a unit mod N
    u0 = pow(c1, -1, m) if m > 1 else 1
    u = u0
    while gcd(u, N) != 1:
        u += m
    d1 = (u * d) % N
    best = None
    for k in range(g):
        v = 1 + k * m
        if gcd(v, N) == 1:
            dd = (v * d1) % N
            if best is None or dd < best:
                best = dd
    return (g % N, best)


def p1_orbit(N: int) -> Dict[Tuple[int, int], int]:
    """Enumerate P^1(Z/N) as the SL_2(Z)-orbit of (0:1) (generated by S and T); returns rep -> index.

    The orbit size equals psi(N) iff SL_2(Z) acts transitively, which it does; computing it is Theta(psi(N))."""
    start = p1_normalize(0, 1, N)
    idx = {start: 0}
    stack = [start]
    while stack:
        c, d = stack.pop()
        for (cc, dd) in ((d, -c), (c, c + d), (c, d - c)):
            r = p1_normalize(cc, dd, N)
            if r not in idx:
                idx[r] = len(idx)
                stack.append(r)
    return idx


def _perm(idx, N, fn) -> List[int]:
    out = [0] * len(idx)
    for (c, d), i in idx.items():
        out[i] = idx[p1_normalize(*fn(c, d), N)]
    return out


def cycles(perm: List[int]) -> List[int]:
    seen = [False] * len(perm)
    lens = []
    for i in range(len(perm)):
        if not seen[i]:
            L = 0
            j = i
            while not seen[j]:
                seen[j] = True
                j = perm[j]
                L += 1
            lens.append(L)
    return lens


def orbifold_from_p1(N: int) -> Dict[str, int]:
    """(mu, nu2, nu3, nu_inf, genus) from the explicit right action of SL_2(Z) on P^1(Z/N).

    Row vectors (c, d) act on the right: S = [[0,-1],[1,0]] gives (d, -c); ST = [[0,-1],[1,1]] gives (d, d - c);
    T = [[1,1],[0,1]] gives (c, c + d). Riemann-Hurwitz for the dessin: 2 - 2g = c(S) + c(ST) + c(T) - mu."""
    idx = p1_orbit(N)
    mu = len(idx)
    S = _perm(idx, N, lambda c, d: (d, -c))
    ST = _perm(idx, N, lambda c, d: (d, d - c))
    T = _perm(idx, N, lambda c, d: (c, c + d))
    cS, cST, cT = cycles(S), cycles(ST), cycles(T)
    n2 = sum(1 for L in cS if L == 1)
    n3 = sum(1 for L in cST if L == 1)
    ninf = len(cT)
    two_minus_2g = len(cS) + len(cST) + ninf - mu
    assert two_minus_2g % 2 == 0
    return {"mu": mu, "nu2": n2, "nu3": n3, "nu_inf": ninf, "genus": (2 - two_minus_2g) // 2}


# ---------------------------------------------------------------------------------------------------------------
# Eichler-Selberg trace formula, k = 2, trivial character (Cohen's form), squarefree N, prime l not dividing N
# ---------------------------------------------------------------------------------------------------------------

def _reduced_forms(D: int) -> List[Tuple[int, int, int]]:
    """Reduced primitive positive-definite forms of discriminant D < 0."""
    out = []
    a = 1
    while 3 * a * a <= -D:
        for b in range(-a + 1, a + 1):
            if (b * b - D) % (4 * a):
                continue
            c = (b * b - D) // (4 * a)
            if c < a:
                continue
            if c == a and b < 0:
                continue
            if gcd(gcd(a, abs(b)), c) != 1:
                continue
            out.append((a, b, c))
        a += 1
    return out


def h_w(D: int) -> Fraction:
    """Class number of primitive forms of discriminant D < 0 with weights 1/2 (D = -4) and 1/3 (D = -3)."""
    h = len(_reduced_forms(D))
    if D == -4:
        return Fraction(h, 2)
    if D == -3:
        return Fraction(h, 3)
    return Fraction(h)


def hurwitz_sum(D: int) -> List[Tuple[int, Fraction]]:
    """[(f, h_w(D/f^2))] over f >= 1 with f^2 | D and D/f^2 = 0, 1 mod 4."""
    out = []
    f = 1
    while f * f <= -D:
        if D % (f * f) == 0 and (D // (f * f)) % 4 in (0, 1):
            out.append((f, h_w(D // (f * f))))
        f += 1
    return out


def sigma1(n: int) -> int:
    return sum(divisors_of(factor_small(n)))


def trace_formula(fN: Fact, l: int, brute: bool = None) -> int:
    """Tr(T_l | S_2(Gamma_0(N))), N squarefree, l prime not dividing N.

    brute=True counts the roots of x^2 - t x + l mod N*N_f by enumeration (small N only); brute=False uses the
    product formula prod_{r|N}(1 + ((t^2-4l)/r)), valid when every prime r | N exceeds 2 sqrt(l)."""
    assert squarefree(fN)
    N = nval(fN)
    assert N % l != 0
    if brute is None:
        brute = N <= 5000
    psiN = psi(fN)
    total = Fraction(sigma1(l))
    # hyperbolic/elliptic terms
    t = 0
    tmax = isqrt(4 * l - 1)
    for t in range(-tmax, tmax + 1):
        D = t * t - 4 * l
        for (f, hw) in hurwitz_sum(D):
            Nf = gcd(N, f)
            if brute:
                K = N * Nf
                M = sum(1 for x in range(N) if (x * x - t * x + l) % K == 0)
            else:
                assert Nf == 1
                M = 1
                for r in fN:
                    assert r * r > 4 * l
                    M *= 1 + kronecker(D, r)
            fq = {r: e for r, e in fN.items() if Nf % r}  # factorisation of N / N_f (N squarefree)
            mu = Fraction(psiN, psi(fq)) * M
            total -= Fraction(1, 2) * hw * mu
    # parabolic term: sum over dd' = l of min(d, d') = 2 (d = 1, l); squarefree N: sum_tau phi(1) = 2^omega
    total -= Fraction(1, 2) * 2 * (2 ** len(fN))
    assert total.denominator == 1
    return int(total)


# ---------------------------------------------------------------------------------------------------------------
# Manin symbols over F_P (independent linear-algebra computation; dimension psi(N))
# ---------------------------------------------------------------------------------------------------------------

P_MOD = 2 ** 31 - 1


def heilbronn_merel(n: int) -> List[Tuple[int, int, int, int]]:
    """Merel's set {[[a,b],[c,d]] : ad - bc = n, a > b >= 0, d > c >= 0}."""
    out = []
    for a in range(1, n + 1):
        for b in range(0, a):
            for d in range(1, n + 1):
                # c = (a d - n) / b  with 0 <= c < d
                if b == 0:
                    if a * d == n:
                        for c in range(0, d):
                            out.append((a, 0, c, d))
                    continue
                num = a * d - n
                if num % b == 0:
                    c = num // b
                    if 0 <= c < d:
                        out.append((a, b, c, d))
    return out


def manin_trace(N: int, l: int) -> Dict[str, int]:
    """dim and Tr(T_l) on the weight-2 modular symbols M_2(Gamma_0(N); F_P), via Manin symbols (only N used)."""
    import flint
    idx = p1_orbit(N)
    n = len(idx)
    rels = []
    for (c, d), i in idx.items():
        j = idx[p1_normalize(d, -c, N)]
        r = [0] * n
        r[i] += 1
        r[j] += 1
        rels.append(r)
        j1 = idx[p1_normalize(d, -c - d, N)]
        j2 = idx[p1_normalize(-c - d, c, N)]
        r = [0] * n
        r[i] += 1
        r[j1] += 1
        r[j2] += 1
        rels.append(r)
    M = flint.nmod_mat(len(rels), n, [x % P_MOD for row in rels for x in row], P_MOD)
    R, rank = M.rref()
    pivots = {}
    for row in range(rank):
        for col in range(n):
            if int(R[row, col]) != 0:
                pivots[col] = row
                break
    free = [col for col in range(n) if col not in pivots]
    free_pos = {col: k for k, col in enumerate(free)}
    H = heilbronn_merel(l)
    tr = 0
    reps = {i: cd for cd, i in idx.items()}
    for col in free:
        c, d = reps[col]
        vec: Dict[int, int] = {}
        for (a, b, cc, dd) in H:
            j = idx[p1_normalize(c * a + d * cc, c * b + d * dd, N)]
            vec[j] = vec.get(j, 0) + 1
        # reduce to quotient coordinates: coefficient on 'col' after replacing pivots
        coef = vec.get(col, 0)
        for j, v in vec.items():
            if j in pivots:
                row = pivots[j]
                coef -= v * int(R[row, col])
        tr = (tr + coef) % P_MOD
    if tr > P_MOD // 2:
        tr -= P_MOD
    return {"dim": len(free), "trace": tr}


# ---------------------------------------------------------------------------------------------------------------
# general n coprime to N (amendment A1): needed for T_{l^2} and point counts over F_{l^2}
# ---------------------------------------------------------------------------------------------------------------

def trace_formula_n(fN: Fact, n: int, brute: bool = None) -> int:
    """Tr(T_n | S_2(Gamma_0(N))), N squarefree, gcd(n, N) = 1 (Cohen's form, k = 2, trivial character).

    A1 = psi(N)/12 if n is a square; A2 = -(1/2) sum_{t^2<4n} sum_f h_w((t^2-4n)/f^2) mu(t,f,n);
    A3 = -(1/2) sum_{d|n} min(d, n/d) * 2^omega(N); A4 = sigma(n)."""
    assert squarefree(fN)
    N = nval(fN)
    assert gcd(n, N) == 1
    if brute is None:
        brute = N <= 5000
    psiN = psi(fN)
    total = Fraction(0)
    r = isqrt(n)
    if r * r == n:
        total += Fraction(psiN, 12)
    tmax = isqrt(4 * n - 1)
    for t in range(-tmax, tmax + 1):
        D = t * t - 4 * n
        for (f, hw) in hurwitz_sum(D):
            Nf = gcd(N, f)
            if brute:
                K = N * Nf
                M = sum(1 for x in range(N) if (x * x - t * x + n) % K == 0)
            else:
                assert Nf == 1
                M = 1
                for rr in fN:
                    assert rr * rr > 4 * n
                    M *= 1 + kronecker(D, rr)
            fq = {q: e for q, e in fN.items() if Nf % q}
            total -= Fraction(1, 2) * hw * Fraction(psiN, psi(fq)) * M
    lam = sum(min(d, n // d) for d in divisors_of(factor_small(n)))
    total -= Fraction(1, 2) * lam * (2 ** len(fN))
    total += sigma1(n)
    assert total.denominator == 1
    return int(total)


def x0_count_sq(fN: Fact, l: int, brute: bool = None) -> int:
    """#X_0(N)(F_{l^2}) = l^2 + 1 - Tr T_{l^2} + l * g   (Weil + Eichler-Shimura + T_l^2 = T_{l^2} + l)."""
    return l * l + 1 - trace_formula_n(fN, l * l, brute) + l * genus(fN)
