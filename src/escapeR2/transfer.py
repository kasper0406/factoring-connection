"""Cross-field parity transfer (Lemma TI of notes/escapeR2_results.md).  DIAGNOSTIC / analysis only; exact.

Setting.  L/Q Galois with group G, subfields K_j = L^{H_j}, an unramified prime l with decomposition group D (cyclic).
Primes of L above l  <->  left cosets gD.  Primes of K_j above l  <->  double cosets H_j g D.  Extension of ideals sends
a prime of K_j to the sum of the primes of L above it (exponent 1, l unramified).  Over F_2 a parity vector of K_j at l
therefore maps to the indicator, on G/D, of a union of double cosets.  Im_j := image of F_2^{H_j \\ G / D}.

Groups are finite permutation groups given by generators; elements are tuples (images of 0..n-1); composition
mul(p, q) = p o q  (apply q first).  F_2 vectors are Python ints (bit i = left coset number i).
"""
from __future__ import annotations

from itertools import combinations, permutations
from typing import Dict, FrozenSet, Iterable, List, Sequence, Tuple

Perm = Tuple[int, ...]


def mul(p: Perm, q: Perm) -> Perm:
    return tuple(p[q[i]] for i in range(len(q)))


def inv(p: Perm) -> Perm:
    r = [0] * len(p)
    for i, x in enumerate(p):
        r[x] = i
    return tuple(r)


def identity(n: int) -> Perm:
    return tuple(range(n))


def closure(gens: Iterable[Perm], n: int) -> FrozenSet[Perm]:
    """The subgroup generated by gens (BFS)."""
    e = identity(n)
    gens = [g for g in gens]
    seen = {e}
    frontier = [e]
    while frontier:
        new = []
        for x in frontier:
            for g in gens:
                y = mul(x, g)
                if y not in seen:
                    seen.add(y)
                    new.append(y)
        frontier = new
    return frozenset(seen)


# ------------------------------------------------------------------ concrete groups
def symmetric(n: int) -> FrozenSet[Perm]:
    return frozenset(permutations(range(n)))


def direct_product(sizes: Sequence[int]) -> Tuple[FrozenSet[Perm], List[List[int]]]:
    """S_{n_1} x ... x S_{n_k} acting on disjoint blocks; returns (group, blocks)."""
    n = sum(sizes)
    blocks, off = [], 0
    for s in sizes:
        blocks.append(list(range(off, off + s)))
        off += s
    gens = []
    for b in blocks:
        if len(b) >= 2:
            for i in range(len(b) - 1):  # adjacent transpositions inside the block
                p = list(range(n))
                p[b[i]], p[b[i + 1]] = p[b[i + 1]], p[b[i]]
                gens.append(tuple(p))
    return closure(gens, n), blocks


def stabiliser(G: FrozenSet[Perm], point: int) -> FrozenSet[Perm]:
    return frozenset(g for g in G if g[point] == point)


# ------------------------------------------------------------------ cosets and F_2 linear algebra
def left_cosets(G: FrozenSet[Perm], D: FrozenSet[Perm]) -> Tuple[List[FrozenSet[Perm]], Dict[Perm, int]]:
    """Left cosets gD of D in G, and the index map element -> coset number."""
    idx: Dict[Perm, int] = {}
    cos: List[FrozenSet[Perm]] = []
    for g in sorted(G):
        if g in idx:
            continue
        c = frozenset(mul(g, d) for d in D)
        for x in c:
            idx[x] = len(cos)
        cos.append(c)
    return cos, idx


def image_basis(G: FrozenSet[Perm], H: FrozenSet[Perm], D: FrozenSet[Perm]) -> List[int]:
    """Indicator vectors (bitmasks over G/D) of the double cosets H g D: a basis of Im_H."""
    cos, idx = left_cosets(G, D)
    done = [False] * len(cos)
    basis = []
    for i, c in enumerate(cos):
        if done[i]:
            continue
        g = next(iter(c))
        mask = 0
        for h in H:
            j = idx[mul(h, g)]
            if not done[j]:
                done[j] = True
            mask |= 1 << j
        basis.append(mask)
    return basis


def rank_f2(vectors: Iterable[int]) -> int:
    piv: Dict[int, int] = {}
    r = 0
    for v in vectors:
        while v:
            h = v.bit_length() - 1
            if h in piv:
                v ^= piv[h]
            else:
                piv[h] = v
                r += 1
                break
    return r


def dim_intersection(A: List[int], B: List[int]) -> int:
    """dim(span A ∩ span B) = dim A + dim B - dim(A + B)."""
    return rank_f2(A) + rank_f2(B) - rank_f2(A + B)


def generated(G_elems: Iterable[FrozenSet[Perm]], n: int) -> FrozenSet[Perm]:
    gens = set()
    for S in G_elems:
        gens |= set(S)
    return closure(gens, n)


def transfer_report(G: FrozenSet[Perm], Hs: Sequence[FrozenSet[Perm]], D: FrozenSet[Perm]) -> Dict[str, int]:
    """For K_1 = L^{H_1} against K_2..K_J: tau, the Lemma TI bound, and the two-field quantity tau_2.

    tau        = dim(Im_1 ∩ sum_{j>=2} Im_j) - 1
    bound      = dim F_2^{H1plus \\ G / D} - 1,  H1plus = <H_1, ∩_{j>=2} H_j>   (fixed field K_1 ∩ K_2...K_J)
    tau2       = dim(Im_1 ∩ Im_2) - dim F_2^{<H_1,H_2> \\ G / D}   (only for J = 2)
    """
    n = len(next(iter(G)))
    ims = [image_basis(G, H, D) for H in Hs]
    others: List[int] = []
    for b in ims[1:]:
        others += b
    tau = dim_intersection(ims[0], others) - 1
    Hp = frozenset.intersection(*Hs[1:])
    H1plus = generated([Hs[0], Hp], n)
    bound = len(image_basis(G, H1plus, D)) - 1
    out = {"tau": tau, "bound": bound, "trivial_meet": int(len(H1plus) == len(G))}
    if len(Hs) == 2:
        H12 = generated([Hs[0], Hs[1]], n)
        out["tau2"] = dim_intersection(ims[0], ims[1]) - len(image_basis(G, H12, D))
    return out


def cyclic_subgroups(G: FrozenSet[Perm]) -> List[FrozenSet[Perm]]:
    """One cyclic subgroup <g> per conjugacy class of g (decomposition groups at unramified primes)."""
    n = len(next(iter(G)))
    seen_cls = set()
    out = []
    for g in sorted(G):
        if g in seen_cls:
            continue
        cls = {mul(mul(x, g), inv(x)) for x in G}
        seen_cls |= cls
        out.append(closure([g], n))
    return out


def subgroups_two_generated(G: FrozenSet[Perm]) -> List[FrozenSet[Perm]]:
    """All subgroups generated by <= 2 elements (proper, non-trivial), deduplicated."""
    n = len(next(iter(G)))
    els = sorted(G)
    subs = set()
    for a in els:
        subs.add(closure([a], n))
    for a, b in combinations(els, 2):
        subs.add(closure([a, b], n))
    return sorted((S for S in subs if 1 < len(S) < len(G)), key=lambda S: (len(S), sorted(S)))


# ------------------------------------------------------------------ named small groups for the census
def group_from_gens(gens: Sequence[Perm]) -> FrozenSet[Perm]:
    return closure(gens, len(gens[0]))


def census_groups() -> Dict[str, FrozenSet[Perm]]:
    return {
        "S4": symmetric(4),
        "D4": group_from_gens([(1, 2, 3, 0), (0, 3, 2, 1)]),
        "A4": group_from_gens([(1, 2, 0, 3), (0, 2, 3, 1)]),
        "C2^3": group_from_gens([(1, 0, 2, 3, 4, 5), (0, 1, 3, 2, 4, 5), (0, 1, 2, 3, 5, 4)]),
        "S3xC2": group_from_gens([(1, 0, 2, 3, 4), (0, 2, 1, 3, 4), (0, 1, 2, 4, 3)]),
    }


def v4() -> Tuple[FrozenSet[Perm], List[FrozenSet[Perm]]]:
    """V4 acting regularly on 4 points, and its three subgroups of order 2."""
    a, b = (1, 0, 3, 2), (2, 3, 0, 1)
    G = group_from_gens([a, b])
    c = mul(a, b)
    return G, [closure([x], 4) for x in (c, a, b)]   # H_1 = <ab>: K_1 = Q(sqrt(ab)) when K_2 = Q(sqrt a), K_3 = Q(sqrt b)
