# Harvey 2021 Alg. 4.1 (product tree over giants, Bluestein over the
# geometric babies alpha^i), fully charged -- used for the HH baseline.
# ---------------------------------------------------------------------------
class _FactorFound(Exception):
    def __init__(self, d: int, how: str):
        self.d, self.how = d, how


def harvey_find_collisions(N: int, alpha: int, kappa: int, vals: List[int], met) -> Optional[int]:
    """Same interface/semantics as src.cycloharvey.operational.find_collisions,
    but over fmpz_mod_poly (any N) and with every scalar multiplication charged:
    the chirp powers alpha^{C(i,2)} are generated by the recurrences
    alpha^{C(i+1,2)} = alpha^{C(i,2)} * alpha^i (two multiplications per index)."""
    if not vals:
        return None
    ctx = flint.fmpz_mod_poly_ctx(N)
    f = product_poly(ctx, vals, met)
    n = f.degree()
    fc = [int(c) for c in f.coeffs()] + [0] * (n + 1 - len(f.coeffs()))
    met.inc("gcdN")
    if gcd(alpha, N) != 1:
        g = gcd(alpha, N)
        if 1 < g < N:
            met.set("hit", None)
            return g
        return None
    ainv = pow(alpha, -1, N)
    met.inc("invN")

    def chirp(base: int, count: int) -> List[int]:
        # base^{C(k,2)} for k = 0..count-1:  C(k+1,2) = C(k,2) + k
        out, cur, bk = [], 1, 1        # cur = base^{C(k,2)}, bk = base^k
        for k in range(count):
            out.append(cur)
            cur = cur * bk % N
            bk = bk * base % N
            met.inc("mulN", 2)
        return out

    h = chirp(alpha, max(kappa, n + 2))           # alpha^{C(i,2)}, i >= 0
    fpj = []
    # alpha^{C(j+1,2)} = h[j+1]
    for j in range(n + 1):
        fpj.append(h[j + 1] * fc[j] % N)
    met.inc("mulN", n + 1)
    # g_k = alpha^{-C(k,2)} for k in [-n, kappa): C(-k,2) = C(k+1,2)
    gpos = chirp(ainv, max(kappa, n + 2))         # ainv^{C(k,2)}, k >= 0
    gk = [gpos[k + 1] for k in range(n, 0, -1)] + [gpos[k] for k in range(kappa)]
    F = ctx(fpj)
    G = ctx(gk)
    P = poly_mul(F, G, met)
    pc = [int(c) for c in P.coeffs()]
    ai = 1
    for i in range(kappa):
        idx = i + n
        s = pc[idx] if idx < len(pc) else 0
        e = h[i] * s % N
        met.inc("mulN")
        met.inc("gcdN")
        g = gcd(e, N)
        if g > 1:
            for hh, v in enumerate(vals):
                met.inc("gcdN")
                g2 = gcd((v - ai) % N, N)
                if 1 < g2 < N:
                    met.set("hit", [i, hh])
                    return g2
        ai = ai * alpha % N
        met.inc("mulN")
    return None
