"""Instrumented polynomial collision detection over Z/N (any N; fmpz_mod_poly).

OPERATIONAL helpers: see only N and ring elements.  Only multiplication and
division by MONIC polynomials are used, so everything is valid over the ring
Z/N with N composite.  No gcd/xgcd/factor of polynomials over Z/N is called.

Cost charging (notes/dcltheorem_prereg.md, metric E):
  poly_cost += (d + 1) * ceil(log2(d + 2))   for every product / remainder whose
               result (product) or dividend (remainder) has degree d
  (FFT-model M(d) in Z/N-multiplication equivalents).  Scalar multiplications
  mod N are charged in mulN; gcds with N in gcdN.
"""
from __future__ import annotations

from math import gcd
from typing import List, Optional, Tuple

import flint


def _pc(d: int) -> int:
    d = max(0, d)
    return (d + 1) * max(1, (d + 1).bit_length())


def poly_mul(a, b, met):
    met.inc("poly_ops")
    met.inc("poly_cost", _pc(a.degree() + b.degree()))
    return a * b


def poly_rem(a, b, met):
    met.inc("poly_ops")
    met.inc("poly_cost", _pc(a.degree()))
    if a.degree() < b.degree():
        return a
    return a % b


def tree_levels(ctx, pts: List[int], met):
    """Product tree of the linear polynomials X - x (bottom level first)."""
    levels = [[ctx([(-x), 1]) for x in pts]]
    while len(levels[-1]) > 1:
        cur, nxt = levels[-1], []
        for i in range(0, len(cur) - 1, 2):
            nxt.append(poly_mul(cur[i], cur[i + 1], met))
        if len(cur) % 2:
            nxt.append(cur[-1])
        levels.append(nxt)
    return levels


def product_poly(ctx, pts: List[int], met):
    return tree_levels(ctx, pts, met)[-1][0]


def multipoint(ctx, f, pts: List[int], met) -> List[int]:
    """f(x) for all x in pts by a remainder tree (monic divisors only)."""
    if not pts:
        return []
    levels = tree_levels(ctx, pts, met)
    rems = [poly_rem(f, levels[-1][0], met)]
    for lev in range(len(levels) - 2, -1, -1):
        cur, new = levels[lev], []
        for i, node in enumerate(cur):
            new.append(poly_rem(rems[i // 2], node, met))
        rems = new
    out = []
    for r in rems:
        c = r.coeffs()
        out.append(int(c[0]) if c else 0)
    return out


def eval_baby_poly_at_giants(N: int, gamma: int, m: int, giants: List[int], met) -> List[int]:
    """f(G) for f(X) = prod_{0<=i<m} (X - gamma^i), for every giant G.
    Baby powers gamma^i are charged (m-1 multiplications)."""
    ctx = flint.fmpz_mod_poly_ctx(N)
    babies, x = [], 1
    for i in range(m):
        babies.append(x)
        x = x * gamma % N
        met.inc("mulN")
    f = product_poly(ctx, babies, met)
    return multipoint(ctx, f, giants, met)


