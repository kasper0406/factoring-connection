#!/usr/bin/env python3
"""Generate leanA/Challenge.lean from the proof layer.

Challenge.lean = the trusted definitions (LeanA/Defs.lean, LeanA/DefsNFS.lean, verbatim)
+ every hypothesis definition (docstring starting PUBLISHED INPUT / INTERNAL HYPOTHESIS, or one of
the cost-model declarations listed in KEEP_DEFS) + every theorem whose docstring starts with MAIN,
with its proof replaced by `sorry`. Helper lemmas and helper definitions are dropped.

Comparator then checks that each MAIN theorem of the solution (module LeanA) has exactly the same
statement as here, and that every constant those statements mention is identical in both.
Run from leanA/:  python3 scripts/gen_challenge.py
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DEF_FILES = ["LeanA/Defs.lean", "LeanA/DefsNFS.lean"]
STMT_FILES = ["LeanA/Exponents.lean", "LeanA/Fruitfulness.lean", "LeanA/SplitCounting.lean",
              "LeanA/Moments.lean", "LeanA/Kern.lean", "LeanA/Recursion.lean",
              "LeanA/RelationSupply.lean", "LeanA/MainTheorems.lean", "LeanA/LiftAveraging.lean"]
KEEP_DEFS = {"supSplit", "CostModelA", "CostInterfaceA", "CostModelRA", "CostInterfaceRA"}
TOP = re.compile(r"^(/--|/-!|theorem |lemma |def |abbrev |structure |private |protected |noncomputable |"
                 r"@\[|section|end |end$|namespace |open |variable |instance |set_option |#)")

def body(path):
    """Text of a file after its imports and module docstring header."""
    lines = (ROOT / path).read_text().splitlines()
    i = 0
    while i < len(lines) and (lines[i].startswith("import ") or not lines[i].strip()):
        i += 1
    return lines[i:]

def chunks(lines):
    """Split into top-level chunks; a docstring is glued to the declaration that follows it."""
    out, cur, in_doc, doc_only = [], [], False, False
    for ln in lines:
        if in_doc:
            cur.append(ln)
            if "-/" in ln:
                in_doc = False
            continue
        if ln.startswith("/--"):
            if cur:
                out.append(cur)
            cur, doc_only = [ln], True
            in_doc = "-/" not in ln[3:]
            continue
        if TOP.match(ln):
            if doc_only:
                cur.append(ln); doc_only = False
                continue
            if cur:
                out.append(cur)
            cur = [ln]
            in_doc = ln.startswith("/-!") and "-/" not in ln[3:]
            continue
        cur.append(ln)
    if cur:
        out.append(cur)
    return out

def decl_name(ch):
    for ln in ch:
        m = re.match(r"^(?:noncomputable |private |protected )*(theorem|lemma|def|abbrev|structure) (\S+)", ln)
        if m:
            return m.group(1), m.group(2)
    return None, None

def doc(ch):
    return ch[0][3:].lstrip() if ch and ch[0].startswith("/--") else ""

def stmt_only(ch):
    text = "\n".join(ch)
    k = text.find(":= by")
    if k < 0:
        sys.exit("MAIN theorem without ':= by': " + text[:200])
    return text[:k] + ":= by\n  sorry"

def main():
    out = ["import Mathlib", "",
           "/-!",
           "# Challenge: trusted statements for the conditional formalisation of Theorem A / RA / P",
           "",
           "GENERATED by `scripts/gen_challenge.py` from the proof layer; do not edit by hand.",
           "Every `sorry` below is an intentional specification placeholder. The proof module `LeanA`",
           "never imports this file. Comparator (`comparator.json`) checks that each theorem here is",
           "proved in `LeanA` with the same statement, using only `propext`, `Quot.sound` and",
           "`Classical.choice`. All analytic and algorithmic inputs are explicit hypotheses (`Prop`s",
           "passed as arguments): PUBLISHED INPUT (published theorems, with citations) and INTERNAL",
           "HYPOTHESIS / cost-model interfaces (the project's own unrefereed claims). There are no `axiom`s.",
           "-/", "", "set_option autoImplicit false", ""]
    for f in DEF_FILES:
        out.append(f"-- ===== verbatim from {f} =====")
        out.extend(body(f)); out.append("")
    for f in STMT_FILES:
        out += [f"-- ===== statements from {f} =====", "", "noncomputable section", "open Classical", "",
                "namespace FactoringA", "", "open Real Finset Filter Topology", ""]
        for ch in chunks(body(f)):
            kind, name = decl_name(ch)
            d = doc(ch)
            if kind in ("theorem", "lemma") and d.startswith("MAIN"):
                out.append(stmt_only(ch)); out.append("")
            elif kind in ("def", "structure", "abbrev") and (
                    d.startswith("PUBLISHED INPUT") or d.startswith("INTERNAL HYPOTHESIS") or d.startswith("TRUSTED") or name in KEEP_DEFS):
                text = "\n".join(ch).rstrip()
                out.append(text); out.append("")
        out += ["end FactoringA", ""]
    (ROOT / "Challenge.lean").write_text("\n".join(out) + "\n")
    names = re.findall(r"^theorem (\S+)", "\n".join(out), re.M)
    cfg = {"challenge_module": "Challenge", "solution_module": "LeanA",
           "theorem_names": ["FactoringA." + n for n in names], "definition_names": [],
           "permitted_axioms": ["propext", "Quot.sound", "Classical.choice"], "enable_nanoda": True}
    import json
    (ROOT / "comparator.json").write_text(json.dumps(cfg, indent=2) + "\n")
    ax = ["/- GENERATED by scripts/gen_challenge.py. Run: `lake env lean AxiomCheck.lean`.",
          "   Expected for every line: [propext, Classical.choice, Quot.sound] (no sorryAx, no custom axiom). -/",
          "import LeanA", ""] + [f"#print axioms FactoringA.{n}" for n in names]
    (ROOT / "AxiomCheck.lean").write_text("\n".join(ax) + "\n")
    print(f"wrote Challenge.lean, comparator.json, AxiomCheck.lean ({len(names)} theorems)")

if __name__ == "__main__":
    main()
