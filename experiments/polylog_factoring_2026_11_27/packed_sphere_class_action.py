"""Binary ideal-class powers acting on the packed near-square ternary sphere."""

from math import gcd
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from src.nonsmooth.forms import disc, power

if __package__:
    from .four_square_sampler import _left_gcd
    from .packed_point_rotations import rotate_integrally
    from .packed_ternary_decision import _packing_parameters
else:
    from four_square_sampler import _left_gcd
    from packed_point_rotations import rotate_integrally
    from packed_ternary_decision import _packing_parameters


def packed_class_power(n, x, form, exponent=1):
    """Return the reduced powered form and one sphere point in its proper rotation orbit.

    The form is primitive positive definite of discriminant −4((x+QN)²+1).
    The construction uses the ideal (a,b/2+W₀) for the powered form (a,b,c).
    """
    scale, m = _packing_parameters(n, x)
    if form[0] <= 0 or disc(form) != -4 * m or gcd(*form) != 1:
        raise ValueError("expected a primitive positive definite form of discriminant −4M")
    if not isinstance(exponent, int) or exponent < 0:
        raise ValueError("expected a nonnegative integer exponent")
    reduced = power(form, exponent)
    a, b, _ = reduced
    height = x + scale * n
    # Conjugation turns the left ideal generated by a and b/2+W₀ into a
    # right ideal. The existing Hurwitz gcd takes doubled coordinates.
    scalar, i, j, k = _left_gcd((2 * a, 0, 0, 0), (b, -2 * height, -2, 0))
    doubled_generator = (scalar, -i, -j, -k)
    if sum(t * t for t in doubled_generator) != 4 * a:
        raise ArithmeticError("Hurwitz ideal generator has unexpected norm")
    point = rotate_integrally(doubled_generator, (height, 1, 0))
    if point is None or gcd(*point) != 1:
        raise ArithmeticError("conjugation did not preserve the optimal embedding")
    return reduced, point
