"""Construct the primitive ternary embedding and its Gaussian projective residue."""

from math import gcd, isqrt

if __package__:
    from .four_square_sampler import _doubled_units, _left_gcd, _multiply
    from .ternary_sphere import hopf_point
else:
    from four_square_sampler import _doubled_units, _left_gcd, _multiply
    from ternary_sphere import hopf_point


def _conj(z):
    return z[0], -z[1]


def _mul(z, w):
    return z[0]*w[0] - z[1]*w[1], z[0]*w[1] + z[1]*w[0]


def _sub(z, w):
    return z[0] - w[0], z[1] - w[1]


def _norm(z):
    return z[0]**2 + z[1]**2


def _gaussian_bezout(a, b):
    """Return d,s,t with d=gcd(a,b)=sa+tb in Z[i], up to a unit."""
    s0, s1 = (1, 0), (0, 0)
    t0, t1 = (0, 0), (1, 0)
    while b != (0, 0):
        denom = _norm(b)
        quotient = tuple((2*c + denom) // (2*denom) for c in _mul(a, _conj(b)))
        a, b = b, _sub(a, _mul(quotient, b))
        s0, s1 = s1, _sub(s0, _mul(quotient, s1))
        t0, t1 = t1, _sub(t0, _mul(quotient, t1))
    return a, s0, t0


def point_from_residue(n, t):
    """Return a primitive point of radius odd n for a residue of norm -1.

    For h=a+bj the left ideal b=t*a mod n is generated by n and 1+t*j.
    Conjugate the generators to use the existing greatest common left divisor.
    This deterministically selects one of the integral norm-n generators.
    """
    if n < 1 or n % 2 == 0 or (_norm(t) + 1) % n:
        raise ValueError("expected odd positive radius and a residue of norm -1")
    x, y = (c % n for c in t)
    generator = _left_gcd((2*n, 0, 0, 0), (2, 0, -2*x, -2*y))
    for unit in _doubled_units():
        product = _multiply(generator, unit)
        if all(c % 4 == 0 for c in product):
            real, imag, j_part, k_part = (c // 4 for c in product)
            # Conjugate back; the sphere sampler writes its second Gaussian
            # coordinate as i*bar(b), hence swaps j and k after conjugation.
            return hopf_point((real, -imag, -k_part, -j_part))
    raise ArithmeticError("odd norm ideal has no integral generator")


def residue_from_quaternion(row, n=None):
    """Return t of norm -1 for the existing hopf_point row; a unit choice can negate t."""
    a = (row[0], row[1])
    b = (row[3], row[2])
    radius = _norm(a) + _norm(b)
    if n is not None and n != radius:
        raise ValueError("quaternion norm differs from the requested radius")
    if radius < 1 or radius % 2 == 0:
        raise ValueError("expected positive odd quaternion norm")
    d, s, v = _gaussian_bezout(a, _conj(b))
    if _norm(d) != 1:
        raise ValueError("the Hopf point is imprimitive")
    # s*a + v*bar(b)=d; the desired t sends a to b and bar(b) to -bar(a).
    value = _mul(_conj(d), _sub(_mul(s, b), _mul(v, _conj(a))))
    return tuple(c % radius for c in value)


def _radius(point):
    squared = sum(c*c for c in point)
    n = isqrt(squared)
    if len(point) != 3 or n*n != squared or n % 2 == 0 or gcd(*point) != 1:
        raise ValueError("expected a primitive ternary point of positive odd radius")
    return n


def residue_from_point(point):
    """Return a norm-minus-one residue for the oriented perpendicular form.

    A cyclic rotation first makes the unique odd coordinate longitudinal.
    Different integral Hopf lifts change the resulting residue by a global sign.
    """
    n = _radius(point)
    if n == 1:
        return (0, 0)
    axis = next(i for i, c in enumerate(point) if c % 2)
    x, y, z = tuple(point)[axis:] + tuple(point)[:axis]
    # Writing y/2+iz/2 = U*bar(V), we have gcd(|U|²,U*bar(V))=U
    # up to a Gaussian unit, since U and V are coprime.
    cross = y // 2, z // 2
    u, _, _ = _gaussian_bezout(((n + x) // 2, 0), cross)
    denominator = _norm(u)
    numerator = _mul(cross, _conj(u))
    if not denominator or any(c % denominator for c in numerator):
        raise ArithmeticError("invalid primitive Hopf lift")
    conjugate_v = tuple(c // denominator for c in numerator)
    return residue_from_quaternion((*u, *_conj(conjugate_v)), n)


def residue_matching_norm_minus_one(z, point):
    """Return c with c²=-Norm(z) mod n if the unoriented perpendicular class matches.

    For any Gaussian unit residue z this explicitly checks both orientations and
    all four global units. A different class returns None.
    """
    n = _radius(point)
    if gcd(_norm(z), n) != 1:
        raise ValueError("expected a Gaussian unit residue")
    t = residue_from_point(point)
    for candidate in (t, _conj(t)):
        # 1/candidate = -bar(candidate); the overall sign of c is immaterial.
        real, imag = (c % n for c in _mul(z, _conj(candidate)))
        if not imag:
            return real
        if not real:
            return imag
    return None
